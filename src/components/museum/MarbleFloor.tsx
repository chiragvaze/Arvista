"use client";

import { useEffect, useMemo, useRef } from "react";
import { useFrame } from "@react-three/fiber";
import {
  HalfFloatType,
  LinearFilter,
  LinearMipmapLinearFilter,
  Matrix4,
  MeshStandardMaterial,
  PerspectiveCamera,
  Plane,
  PlaneGeometry,
  Vector3,
  Vector4,
  WebGLRenderTarget,
  type Mesh,
  type WebGLProgramParametersWithUniforms,
} from "three";
import type { QualityTier } from "@/lib/museum/deviceTier";
import { scaleUVs } from "@/lib/museum/geometry";
import { bakeFloor, fitToMetres } from "@/lib/museum/lightmaps";
import { CORRIDOR, PLANTER_SPOTS } from "@/lib/museum/layout";
import { useMuseumMaterials } from "./materials";
import { useDisposable } from "./helpers";

const WIDTH = 34;
const NEAR_Z = 30;
/** Runs past the end wall and under the apse. */
const FAR_Z = CORRIDOR.endZ - 12;
/** One texture repeat holds 2 x 2 marble slabs of 1.5 m. */
const METRES_PER_REPEAT = 3;

/** Size of the reflection render; its softness comes from sampling a blurrier mip level as well. */
const REFLECTION_SIZE = 256;
/** Mip level blended in for a polished-stone (not mirror) softness, and its share. */
const REFLECTION_BLUR = { lod: 2.2, mix: 0.55 } as const;

/** Screen points (normalised device coordinates) along the bottom and lower sides, used to test whether the floor is in view. */
const FLOOR_PROBES: readonly [number, number][] = [
  [-1, -1],
  [0, -1],
  [1, -1],
  [-1, -0.35],
  [1, -0.35],
];

/**
 * Whether any of the floor is visible. Inside the corridor its walls hide the
 * floor beyond them, so a screen point counts only if its view ray reaches the
 * floor between the walls (or through the final archway); in the portico and
 * forecourt the floor always counts as visible. When the camera is turned to a
 * painting the floor is out of sight and the reflection is not rendered.
 */
function floorInView(camera: PerspectiveCamera, origin: Vector3, ray: Vector3): boolean {
  origin.setFromMatrixPosition(camera.matrixWorld);
  if (origin.z > CORRIDOR.startZ - 0.5) return true;
  for (const [x, y] of FLOOR_PROBES) {
    ray.set(x, y, 0.5).unproject(camera).sub(origin);
    if (ray.y >= -1e-4) continue;
    const t = -origin.y / ray.y;
    const hitX = origin.x + ray.x * t;
    const hitZ = origin.z + ray.z * t;
    if (Math.abs(hitX) < CORRIDOR.halfWidth && hitZ > FAR_Z && hitZ < CORRIDOR.startZ) return true;
  }
  return false;
}

/**
 * A planar reflection in the floor: the scene is rendered from the camera's
 * mirror image below the floor into a small texture, which the floor samples
 * in screen-projected coordinates. The mirror-camera and oblique-clipping maths
 * follow three.js's Reflector (as drei's MeshReflectorMaterial does).
 *
 * Compared with drei's reflector, which it replaces with the same look, it:
 * - softens the reflection by sampling the texture's mipmaps (generated by the
 *   GPU after each render) instead of running five full-texture blur passes;
 * - skips the render entirely when the floor is out of view;
 * - renders only layer 0, so details on DETAIL_LAYER are left out of it.
 */
class PlanarReflection {
  readonly target = new WebGLRenderTarget(REFLECTION_SIZE, REFLECTION_SIZE, {
    type: HalfFloatType,
    minFilter: LinearMipmapLinearFilter,
    magFilter: LinearFilter,
    generateMipmaps: true,
  });
  /** Maps floor-local positions to reflection texture coordinates (projective). */
  readonly textureMatrix = new Matrix4();
  readonly camera = new PerspectiveCamera();
  private readonly normal = new Vector3();
  private readonly planePoint = new Vector3();
  private readonly cameraPosition = new Vector3();
  private readonly rotation = new Matrix4();
  private readonly lookAt = new Vector3();
  private readonly view = new Vector3();
  private readonly lookTarget = new Vector3();
  private readonly plane = new Plane();
  private readonly clipPlane = new Vector4();
  private readonly q = new Vector4();

  /** Positions the mirror camera for this frame; false when the camera is below the floor. */
  update(camera: PerspectiveCamera, floor: Mesh): boolean {
    this.planePoint.setFromMatrixPosition(floor.matrixWorld);
    this.cameraPosition.setFromMatrixPosition(camera.matrixWorld);
    this.rotation.extractRotation(floor.matrixWorld);
    // The floor's plane geometry faces +Z; the mesh's rotation lays it flat.
    this.normal.set(0, 0, 1).applyMatrix4(this.rotation);
    this.view.subVectors(this.planePoint, this.cameraPosition);
    if (this.view.dot(this.normal) > 0) return false;
    this.view.reflect(this.normal).negate().add(this.planePoint);

    this.rotation.extractRotation(camera.matrixWorld);
    this.lookAt.set(0, 0, -1).applyMatrix4(this.rotation).add(this.cameraPosition);
    this.lookTarget.subVectors(this.planePoint, this.lookAt).reflect(this.normal).negate().add(this.planePoint);

    const mirror = this.camera;
    mirror.position.copy(this.view);
    mirror.up.set(0, 1, 0).applyMatrix4(this.rotation).reflect(this.normal);
    mirror.lookAt(this.lookTarget);
    mirror.far = camera.far;
    mirror.updateMatrixWorld();
    mirror.projectionMatrix.copy(camera.projectionMatrix);

    this.textureMatrix.set(0.5, 0, 0, 0.5, 0, 0.5, 0, 0.5, 0, 0, 0.5, 0.5, 0, 0, 0, 1);
    this.textureMatrix.multiply(mirror.projectionMatrix).multiply(mirror.matrixWorldInverse).multiply(floor.matrixWorld);

    // Oblique near plane at the floor, so nothing below it appears in the reflection
    // (http://www.terathon.com/lengyel/Lengyel-Oblique.pdf).
    this.plane.setFromNormalAndCoplanarPoint(this.normal, this.planePoint).applyMatrix4(mirror.matrixWorldInverse);
    this.clipPlane.set(this.plane.normal.x, this.plane.normal.y, this.plane.normal.z, this.plane.constant);
    const e = mirror.projectionMatrix.elements;
    this.q.set((Math.sign(this.clipPlane.x) + e[8]) / e[0], (Math.sign(this.clipPlane.y) + e[9]) / e[5], -1, (1 + e[10]) / e[14]);
    this.clipPlane.multiplyScalar(2 / this.clipPlane.dot(this.q));
    e[2] = this.clipPlane.x;
    e[6] = this.clipPlane.y;
    e[10] = this.clipPlane.z + 1;
    e[14] = this.clipPlane.w;
    return true;
  }

  dispose() {
    this.target.dispose();
  }
}

/**
 * Polished marble: the lit stone plus the reflection added on top, weighted by
 * Fresnel reflectance (about 4% looking straight down, rising toward grazing
 * angles), so the floor reflects faintly underfoot and clearly down the corridor.
 */
function makeReflective(material: MeshStandardMaterial, reflection: PlanarReflection): MeshStandardMaterial {
  const uniforms = {
    reflectionMap: { value: reflection.target.texture },
    reflectionMatrix: { value: reflection.textureMatrix },
    reflectionLod: { value: REFLECTION_BLUR.lod },
    reflectionBlurMix: { value: REFLECTION_BLUR.mix },
  };
  material.onBeforeCompile = (shader: WebGLProgramParametersWithUniforms) => {
    Object.assign(shader.uniforms, uniforms);
    shader.vertexShader = shader.vertexShader
      .replace("#include <common>", "#include <common>\nuniform mat4 reflectionMatrix;\nvarying vec4 vReflectionCoord;")
      .replace("#include <project_vertex>", "#include <project_vertex>\nvReflectionCoord = reflectionMatrix * vec4(transformed, 1.0);");
    shader.fragmentShader = shader.fragmentShader
      .replace(
        "#include <common>",
        "#include <common>\nuniform sampler2D reflectionMap;\nuniform float reflectionLod;\nuniform float reflectionBlurMix;\nvarying vec4 vReflectionCoord;",
      )
      .replace(
        "#include <opaque_fragment>",
        `vec2 reflectionUv = vReflectionCoord.xy / vReflectionCoord.w;
        vec3 reflected = mix(textureLod(reflectionMap, reflectionUv, 0.0).rgb, textureLod(reflectionMap, reflectionUv, reflectionLod).rgb, reflectionBlurMix);
        float reflectionNdotV = saturate(dot(normal, normalize(vViewPosition)));
        outgoingLight += reflected * (0.04 + 0.96 * pow(1.0 - reflectionNdotV, 5.0));
        #include <opaque_fragment>`,
      );
  };
  material.customProgramCacheKey = () => "arvista-floor-reflection";
  return material;
}

/**
 * One continuous polished marble floor running from the forecourt through the
 * corridor, so inside and outside read as a single building. High tier adds the
 * planar reflection; the low tier uses a glossy standard material. Baked
 * contact shadows ground the walls, the planters and the bench.
 */
export function MarbleFloor({ quality }: { quality: QualityTier }) {
  const { marbleMap } = useMuseumMaterials();
  const floor = useRef<Mesh>(null);
  const length = NEAR_Z - FAR_Z;
  const geometry = useDisposable(() => scaleUVs(new PlaneGeometry(WIDTH, length), WIDTH / METRES_PER_REPEAT, length / METRES_PER_REPEAT));
  const ao = useDisposable(() =>
    fitToMetres(bakeFloor(WIDTH, NEAR_Z, FAR_Z, PLANTER_SPOTS), WIDTH / METRES_PER_REPEAT, length / METRES_PER_REPEAT),
  );
  const reflection = useMemo(() => (quality === "high" ? new PlanarReflection() : null), [quality]);
  const material = useMemo(() => {
    const base = new MeshStandardMaterial({ map: marbleMap, aoMap: ao, color: "#d6c9b4", roughness: reflection ? 0.2 : 0.22, metalness: 0 });
    return reflection ? makeReflective(base, reflection) : base;
  }, [marbleMap, ao, reflection]);
  useEffect(
    () => () => {
      material.dispose();
      reflection?.dispose();
    },
    [material, reflection],
  );

  const probe = useMemo(() => ({ origin: new Vector3(), ray: new Vector3() }), []);
  // Runs after the camera has been placed for this frame (MuseumCamera subscribes first).
  useFrame(({ gl, scene, camera }) => {
    const mesh = floor.current;
    if (!reflection || !mesh || !(camera instanceof PerspectiveCamera)) return;
    if (!floorInView(camera, probe.origin, probe.ray) || !reflection.update(camera, mesh)) return;
    const previous = gl.getRenderTarget();
    mesh.visible = false;
    gl.setRenderTarget(reflection.target);
    gl.state.buffers.depth.setMask(true);
    gl.render(scene, reflection.camera);
    gl.setRenderTarget(previous);
    mesh.visible = true;
  });

  return (
    // The plane is laid flat by rotating the mesh, not the geometry: the reflection derives its plane from the
    // mesh's rotation (the geometry faces +Z).
    <mesh
      ref={floor}
      geometry={geometry}
      material={material}
      position={[0, 0, (NEAR_Z + FAR_Z) / 2]}
      rotation={[-Math.PI / 2, 0, 0]}
      receiveShadow
    />
  );
}
